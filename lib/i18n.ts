export function formatMoney(cents: number | undefined, locale: Locale) {
  if (typeof cents !== "number") return "";
  return new Intl.NumberFormat(locale === "fr" ? "fr-CA" : "en-CA", {
    style: "currency",
    currency: "CAD"
  }).format(cents / 100);
}
